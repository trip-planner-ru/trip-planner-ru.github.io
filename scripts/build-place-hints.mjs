// Builds src/data/place_hints.json: the best-known sights of every city in the app, with Russian and English
// names and coordinates. The Map tab suggests them while you type (works offline, in Russian or English).
//
//   npm run update:places            (continues a run that stopped today; add -- --fresh to start over)
//
// Source: Wikidata. Places within a radius of the city centre whose type is a sight (museum, cathedral, square,
// park, …), ranked by how many Wikipedia language editions have an article about them.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const OUT = new URL('../src/data/place_hints.json', import.meta.url);
const LOCATIONS = new URL('../src/data/locations.json', import.meta.url);
const HEADERS = { 'User-Agent': 'TripPlanner/1.0 (https://trip-planner-ru.github.io; place hints builder)', Accept: 'application/sparql-results+json' };
const PER_CITY = 20;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Wikidata type → Russian caption. Only places of these types are kept.
const KINDS = {
  Q33506: 'Музей', Q207694: 'Художественный музей', Q17431399: 'Музей', Q2772772: 'Военный музей', Q588140: 'Научный музей',
  Q1007870: 'Галерея', Q2319498: 'Достопримечательность', Q570116: 'Туристическое место', Q12518: 'Башня',
  Q1440300: 'Смотровая башня', Q11303: 'Небоскрёб', Q2977: 'Собор', Q16970: 'Церковь', Q163687: 'Базилика',
  Q120560: 'Базилика', Q44613: 'Монастырь', Q32815: 'Мечеть', Q34627: 'Синагога', Q44539: 'Храм', Q5393308: 'Буддийский храм',
  Q16560: 'Дворец', Q23413: 'Замок', Q57821: 'Крепость', Q57831: 'Крепость', Q174782: 'Площадь', Q7543083: 'Улица',
  Q79007: 'Улица', Q4989906: 'Памятник', Q143912: 'Триумфальная арка', Q575759: 'Мемориал', Q22698: 'Парк',
  Q1107656: 'Сад', Q167346: 'Ботанический сад', Q39614: 'Кладбище', Q12280: 'Мост', Q153562: 'Опера', Q24354: 'Театр',
  Q1060829: 'Концертный зал', Q483110: 'Стадион', Q43501: 'Зоопарк', Q2281788: 'Аквариум', Q194195: 'Парк развлечений',
  Q37654: 'Рынок', Q330284: 'Рынок', Q40080: 'Пляж', Q123705: 'Район', Q676050: 'Старый город', Q15243209: 'Исторический район',
  Q54050: 'Холм', Q8502: 'Гора', Q23442: 'Остров', Q23397: 'Озеро', Q34038: 'Водопад', Q1497364: 'Архитектурный ансамбль',
  Q811979: 'Архитектурное сооружение', Q839954: 'Археологический памятник', Q19860854: 'Разрушенное здание', Q11315: 'Торговый центр',
  Q1076486: 'Спортивная арена',
};
const RADIUS_KM = { london: 10, tokyo: 12, 'new-york': 10, 'los-angeles': 20, paris: 6, istanbul: 8, bangkok: 10, dubai: 20, miami: 15,
  // resorts: sights are spread far from the centre
  eilat: 30, phuket: 30, 'sharm-el-sheikh': 30, larnaca: 20, paphos: 20, 'abu-dhabi': 25, heraklion: 15, split: 12, dubrovnik: 12, antalya: 15, tivat: 15 };

function query(city, radius) {
  return `
SELECT ?item ?ru ?en ?coord ?links (SAMPLE(?type) AS ?kind) WHERE {
  SERVICE wikibase:around { ?item wdt:P625 ?coord . bd:serviceParam wikibase:center "Point(${city.lng} ${city.lat})"^^geo:wktLiteral . bd:serviceParam wikibase:radius "${radius}" . }
  VALUES ?type { ${Object.keys(KINDS).map((q) => `wd:${q}`).join(' ')} }
  ?item wikibase:sitelinks ?links . FILTER(?links >= 5)
  ?item wdt:P31 ?type .
  ?item rdfs:label ?ru FILTER(lang(?ru) = "ru")
  OPTIONAL { ?item rdfs:label ?en FILTER(lang(?en) = "en") }
} GROUP BY ?item ?ru ?en ?coord ?links ORDER BY DESC(?links) LIMIT ${PER_CITY * 2}`;
}

// Dense city centres can time out (504): retry with a smaller radius; rate limits (429): wait and retry.
async function sparql(city) {
  let radius = RADIUS_KM[city.id] ?? 7;
  for (let attempt = 1; attempt <= 5; attempt++) {
    let res;
    try {
      res = await fetch(`https://query.wikidata.org/sparql?${new URLSearchParams({ query: query(city, radius) })}`, { headers: HEADERS });
    } catch {
      await sleep(10_000); // network hiccup: wait and try again
      continue;
    }
    if (res.ok) return (await res.json()).results.bindings;
    if (res.status === 504) radius = Math.max(2, Math.round(radius * 0.6));
    await sleep(res.status === 429 ? 30_000 : 5_000);
  }
  console.warn(`  ${city.nameRu}: Wikidata did not answer — no hints for this city`);
  return [];
}

const cities = JSON.parse(readFileSync(LOCATIONS, 'utf8')).countries.flatMap((c) => c.cities);
const today = new Date().toISOString().slice(0, 10);
const result = {
  _note: 'Generated by scripts/build-place-hints.mjs from Wikidata (sights near each city centre). Re-run with: npm run update:places',
  generatedAt: today,
  cities: {},
};
// A run that stopped part-way today is continued: cities already fetched today are kept.
const save = () => writeFileSync(OUT, `${JSON.stringify(result, null, 1)}\n`);
if (existsSync(OUT)) {
  const previous = JSON.parse(readFileSync(OUT, 'utf8'));
  if (previous.generatedAt === today && !process.argv.includes('--fresh')) Object.assign(result.cities, previous.cities);
}

for (const city of cities) {
  if (result.cities[city.id]?.length) continue;
  const rows = await sparql(city);
  const seen = new Set();
  const places = [];
  for (const r of rows) {
    const id = r.item.value.split('/').pop();
    const name = r.ru.value;
    if (seen.has(id) || seen.has(name.toLowerCase()) || name.toLowerCase() === city.nameRu.toLowerCase()) continue;
    seen.add(id);
    seen.add(name.toLowerCase());
    const [lng, lat] = r.coord.value.match(/-?[\d.]+/g).map(Number);
    places.push({
      ru: name,
      ...(r.en && r.en.value !== name ? { en: r.en.value } : {}),
      kind: KINDS[r.kind.value.split('/').pop()],
      lat: Math.round(lat * 1e5) / 1e5,
      lng: Math.round(lng * 1e5) / 1e5,
    });
    if (places.length === PER_CITY) break;
  }
  result.cities[city.id] = places;
  console.log(`${city.nameRu}: ${places.length} — ${places.slice(0, 4).map((p) => p.ru).join(', ')}`);
  save();
  await sleep(2000);
}

// Keep the cities in the same order as the app, whatever order they were fetched in.
result.cities = Object.fromEntries(cities.map((c) => [c.id, result.cities[c.id] ?? []]));
save();
console.log(`Wrote ${Object.values(result.cities).flat().length} places for ${cities.length} cities.`);
